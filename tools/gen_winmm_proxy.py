r"""Generate the export table of the winmm.dll proxy (src/loader/).

usage: python -I tools/gen_winmm_proxy.py [path\to\32-bit\winmm.dll]
       (default: %SystemRoot%\SysWOW64\winmm.dll)

Writes src/loader/winmm_exports.inc (one RMM_PROXY_EXPORT line per export)
and src/loader/winmm.def. Every export of the real DLL gets a stub that jumps
through a pointer the proxy fills from the system winmm.dll at load time.
"""
import os
import struct
import sys

src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "SysWOW64",
                                                          "winmm.dll")
here = os.path.dirname(os.path.abspath(__file__))
out_dir = os.path.join(here, "..", "src", "loader")

d = open(src, "rb").read()
pe = struct.unpack_from("<I", d, 0x3C)[0]
assert struct.unpack_from("<H", d, pe + 24)[0] == 0x10B, "need the 32-bit winmm.dll"
opt = pe + 24
optsize = struct.unpack_from("<H", d, pe + 20)[0]
nsec = struct.unpack_from("<H", d, pe + 6)[0]
exp_rva = struct.unpack_from("<I", d, opt + 96)[0]
secs = [struct.unpack_from("<8sIIII", d, opt + optsize + 40 * i)[1:] for i in range(nsec)]


def r2o(rva):
    for vsize, va, rsize, rptr in secs:
        if va <= rva < va + max(vsize, rsize):
            return rptr + rva - va
    raise ValueError(hex(rva))


def cstr(o):
    return d[o:d.index(b"\0", o)].decode()


o = r2o(exp_rva)
base = struct.unpack_from("<I", d, o + 16)[0]
nfuncs, nnames, af, an, ao = struct.unpack_from("<IIIII", d, o + 20)
named = {}
for i in range(nnames):
    name = cstr(r2o(struct.unpack_from("<I", d, r2o(an) + 4 * i)[0]))
    named[base + struct.unpack_from("<H", d, r2o(ao) + 2 * i)[0]] = name
exports = []
for i in range(nfuncs):
    if struct.unpack_from("<I", d, r2o(af) + 4 * i)[0]:
        exports.append((base + i, named.get(base + i)))

with open(os.path.join(out_dir, "winmm_exports.inc"), "w", newline="\n") as f:
    f.write("// Generated by tools/gen_winmm_proxy.py - do not edit.\n")
    f.write("// RMM_PROXY_EXPORT(index, ordinal, name) - name is \"\" for ordinal-only exports.\n")
    for idx, (ordinal, name) in enumerate(exports):
        f.write(f'RMM_PROXY_EXPORT({idx}, {ordinal}, "{name or ""}")\n')
with open(os.path.join(out_dir, "winmm.def"), "w", newline="\n") as f:
    f.write("; Generated by tools/gen_winmm_proxy.py - do not edit.\n")
    f.write("LIBRARY winmm\nEXPORTS\n")
    for idx, (ordinal, name) in enumerate(exports):
        if name:
            f.write(f"    {name}=rmm_proxy_{idx} @{ordinal}\n")
        else:
            f.write(f"    rmm_proxy_ord{ordinal}=rmm_proxy_{idx} @{ordinal} NONAME\n")
print(f"{len(exports)} exports ({sum(1 for _, n in exports if not n)} ordinal-only) from {src}")
