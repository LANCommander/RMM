void VarRegistry::LoadArchive() {
    std::ifstream f(archivePath_);

    if (!f)
        return;

    std::string line;

    while (std::getline(f, line)) {
        line = Trim(line);

        if (line.empty() || line[0] == ';' || line[0] == '#' || StartsWith(line, "//"))
            continue;

        auto args = SplitArgs(line);

        if (args.size() >= 2)
            SetPending(args[0], args[1]);
    }
}

void VarRegistry::SaveArchive() {
    if (archivePath_.empty())
        return;

    // Merge: keep pending values of vars that are currently not registered.
    std::map<std::string, std::string> out = pending_;

    for (auto& kv : vars_)
        if (kv.second->flags & RMM_VAR_ARCHIVE)
            out[ToLower(kv.second->name)] = kv.second->value;

    std::ofstream f(archivePath_, std::ios::trunc);

    if (!f)
        return;

    f << "// Auto-generated by Refractor MultiMod. Values of RMM_VAR_ARCHIVE variables.\n";

    for (auto& kv : out)
        f << kv.first << " " << QuoteArg(kv.second) << "\n";

    dirty_ = false;
}

void VarRegistry::SetPending(const std::string& name, const std::string& value) { pending_[ToLower(name)] = value; }

rmm_handle_t VarRegistry::Create(Plugin* owner, const std::string& name, const std::string& def,
                                 const std::string& desc, uint32_t flags, std::string* err) {
    if (name.empty() || name.find_first_of(" \t\"") != std::string::npos) {
        if (err)
            *err = "invalid variable name";

        return RMM_INVALID_HANDLE;
    }

    std::string key = ToLower(name);

    if (auto it = byName_.find(key); it != byName_.end()) {
        Var* existing = vars_[it->second].get();

        if (existing->owner == owner)
            return existing->h;  // idempotent re-create

        if (err)
            *err = "variable already owned by another plugin";

        return RMM_INVALID_HANDLE;
    }

    auto v = std::make_unique<Var>();
    v->h = nextHandle_++;
    v->owner = owner;
    v->name = name;
    v->def = def;
    v->desc = desc;
    v->flags = flags;
    v->value = def;

    if (auto p = pending_.find(key); p != pending_.end()) {
        v->value = p->second;
        pending_.erase(p);
    }

    rmm_handle_t h = v->h;
    byName_[key] = h;
    vars_[h] = std::move(v);

    return h;
}

Var* VarRegistry::Get(rmm_handle_t h) {
    auto it = vars_.find(h);

    return it == vars_.end() ? nullptr : it->second.get();
}

Var* VarRegistry::Find(const std::string& name) {
    auto it = byName_.find(ToLower(name));

    return it == byName_.end() ? nullptr : Get(it->second);
}

std::vector<const Var*> VarRegistry::List() const {
    std::vector<const Var*> v;

    for (auto& kv : vars_)
        v.push_back(kv.second.get());

    std::sort(v.begin(), v.end(), [](const Var* a, const Var* b) { return ToLower(a->name) < ToLower(b->name); });

    return v;
}

bool VarRegistry::Set(Plugin* by, Var* v, const std::string& value, std::string* err) {
    if (!v)
        return false;

    if ((v->flags & RMM_VAR_READONLY) && by != v->owner) {
        if (err)
            *err = "variable is read-only";

        return false;
    }

    std::string newValue = value;

    if ((v->flags & RMM_VAR_NUMERIC) || v->hasMin || v->hasMax) {
        double d;

        if (!ParseDouble(value, d)) {
            if (err)
                *err = "value must be numeric";

            return false;
        }

        if (v->hasMin && d < v->min) {
            if (err)
                *err = Format("value below minimum %g", v->min);

            return false;
        }

        if (v->hasMax && d > v->max) {
            if (err)
                *err = Format("value above maximum %g", v->max);

            return false;
        }
    }

    if (newValue == v->value)
        return true;

    std::string old = v->value;
    v->value = newValue;

    if (v->flags & RMM_VAR_ARCHIVE)
        dirty_ = true;

    Core& core = Core::Get();
    rmm_handle_t h = v->h;
    std::string name = v->name;
    bool notify = (v->flags & RMM_VAR_NOTIFY) != 0;
    bool protectedVar = (v->flags & RMM_VAR_PROTECTED) != 0;

    ++firing_;

    for (size_t i = 0; i < hooks_.size(); ++i) {
        ChangeHook hk = hooks_[i];

        if (hk.dead || hk.var != h)
            continue;

        if (hk.owner && hk.owner->state != PluginState::Running)
            continue;

        core.CallPlugin(hk.owner, "var change hook", [&] { hk.cb(h, old.c_str(), newValue.c_str(), hk.user); });
    }

    --firing_;

    if (firing_ == 0)
        hooks_.erase(std::remove_if(hooks_.begin(), hooks_.end(), [](const ChangeHook& c) { return c.dead; }),
                     hooks_.end());

    rmm_ev_var_changed ev{h, name.c_str(), old.c_str(), newValue.c_str()};
    core.Events().Dispatch(RMM_EV_VAR_CHANGED, &ev);

    if (notify)
        core.Chat().Send(ChatQueue::Kind::All, 0,
                         Format("[RMM] %s changed to %s", name.c_str(), protectedVar ? "***" : newValue.c_str()), -1,
                         false);

    if (dirty_ && firing_ == 0)
        SaveArchive();

    return true;
}

rmm_handle_t VarRegistry::HookChange(Plugin* owner, rmm_handle_t var, rmm_var_change_cb cb, void* user) {
    if (!cb || !Get(var))
        return RMM_INVALID_HANDLE;

    ChangeHook hk{nextHandle_++, var, owner, cb, user, false};
    hooks_.push_back(hk);  // index-based iteration in Set() tolerates growth

    return hk.h;
}

bool VarRegistry::UnhookChange(Plugin* owner, rmm_handle_t hook) {
    for (auto& hk : hooks_)
        if (hk.h == hook && hk.owner == owner && !hk.dead) {
            hk.dead = true;

            return true;
        }

    return false;
}

void VarRegistry::RemoveAll(Plugin* owner) {
    for (auto& hk : hooks_)
        if (hk.owner == owner)
            hk.dead = true;

    if (firing_ == 0)
        hooks_.erase(std::remove_if(hooks_.begin(), hooks_.end(), [](const ChangeHook& c) { return c.dead; }),
                     hooks_.end());

    bool changed = false;

    for (auto it = vars_.begin(); it != vars_.end();) {
        Var* v = it->second.get();

        if (v->owner == owner) {
            // Keep the value so a reload picks it back up.
            if (v->value != v->def)
                pending_[ToLower(v->name)] = v->value;

            for (auto& hk : hooks_)
                if (hk.var == v->h)
                    hk.dead = true;

            byName_.erase(ToLower(v->name));
            it = vars_.erase(it);
            changed = true;
        } else {
            ++it;
        }
    }

    for (auto& w : watches_)
        w.owners.erase(std::remove(w.owners.begin(), w.owners.end(), owner), w.owners.end());

    watches_.erase(std::remove_if(watches_.begin(), watches_.end(), [](const WatchRec& w) { return w.owners.empty(); }),
                   watches_.end());

    if (changed && dirty_)
        SaveArchive();
}

void VarRegistry::Watch(Plugin* owner, const std::string& engineVar) {
    for (auto& w : watches_)
        if (IEquals(w.name, engineVar)) {
            if (std::find(w.owners.begin(), w.owners.end(), owner) == w.owners.end())
                w.owners.push_back(owner);

            return;
        }

    watches_.push_back(WatchRec{engineVar, "", false, {owner}});
}

void VarRegistry::PollWatches(double now) {
    if (watches_.empty() || now < nextPoll_)
        return;

    nextPoll_ = now + 1.0;  // engine vars are polled once per second
    Core& core = Core::Get();

    for (size_t i = 0; i < watches_.size(); ++i) {
        std::string value;

        if (!core.Game().GetEngineVar(watches_[i].name, value))
            continue;

        if (!watches_[i].primed) {
            watches_[i].last = value;
            watches_[i].primed = true;
            continue;
        }

        if (value == watches_[i].last)
            continue;

        std::string old = watches_[i].last, name = watches_[i].name;
        watches_[i].last = value;
        rmm_ev_var_changed ev{0, name.c_str(), old.c_str(), value.c_str()};
        core.Events().Dispatch(RMM_EV_VAR_CHANGED, &ev);
    }
}

